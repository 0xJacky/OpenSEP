#ifndef OPEN_SECURE_ROM_RUNTIME_BOOT_BOOTSTRAP_H
#define OPEN_SECURE_ROM_RUNTIME_BOOT_BOOTSTRAP_H

#define SEP_BOOT_ROM_BASE 0x02000000
#define SEP_BOOT_ROM_MAPPED_SIZE 0x00050000

#define SEP_BOOT_RUNTIME_RAM_BASE 0x04020000
#define SEP_BOOT_RUNTIME_RAM_LIMIT 0x04024000
#define SEP_BOOT_EL0_STACK_BOTTOM 0x04028000
#define SEP_BOOT_EL0_STACK_TOP 0x04030000
#define SEP_BOOT_EL0_STACK_PHYSICAL_BOTTOM 0x04024000
#define SEP_BOOT_EL1_STACK_BOTTOM 0x04034000
#define SEP_BOOT_EL1_STACK_TOP 0x04038000
#define SEP_BOOT_EL1_STACK_PHYSICAL_BOTTOM 0x0402c000
#define SEP_BOOT_RUNTIME_CLEAR_BASE 0x04020600
#define SEP_BOOT_RUNTIME_CLEAR_LIMIT 0x04021080
#define SEP_BOOT_RUNTIME_EXTENSION_VA 0x0403c000
#define SEP_BOOT_RUNTIME_EXTENSION_PA 0x04030000
#define SEP_BOOT_RUNTIME_TAIL_VA 0x0404c000
#define SEP_BOOT_RUNTIME_TAIL_PA 0x0403c000

#define SEP_BOOT_ROOT_TABLE 0x04040000
#define SEP_BOOT_ROM_PAGE_TABLE 0x04044000
#define SEP_BOOT_RAM_PAGE_TABLE 0x0404c000
#define SEP_BOOT_TABLE_LIMIT 0x04050000
#define SEP_BOOT_TABLE_ALIAS_VA 0x04054000

#define SEP_BOOT_MAILBOX_VA 0x05000000
#define SEP_BOOT_MAILBOX_PA 0x30250000
#define SEP_BOOT_PLATFORM_MMIO 0x30400000
#define SEP_BOOT_CONFIGURATION_SINK_MMIO 0x30600000
#define SEP_BOOT_DEVICE_BLOCK_VA 0x30000000
#define SEP_BOOT_DEVICE_BLOCK_PA 0x00000000
#define SEP_BOOT_DEVICE_BLOCK_SIZE 0x02000000
#define SEP_BOOT_LOW_APERTURE_VA 0x20000000
#define SEP_BOOT_LOW_APERTURE_PA 0x20000000
#define SEP_BOOT_LOW_APERTURE_BLOCK_COUNT 8
#define SEP_BOOT_RUNTIME_WINDOW_VA 0x0800000000
#define SEP_BOOT_RUNTIME_WINDOW_PA 0x06000000
#define SEP_BOOT_RUNTIME_WINDOW_BLOCK_COUNT 125
#define SEP_BOOT_RUNTIME_WINDOW_EXTENSION_PA 0x0100000000
#define SEP_BOOT_RUNTIME_WINDOW_EXTENSION_BLOCK_COUNT 3

#define SEP_BOOT_PAGE_SIZE 0x00004000
#define SEP_BOOT_ROOT_SHIFT 25
#define SEP_BOOT_PAGE_SHIFT 14
#define SEP_BOOT_TABLE_INDEX_MASK 0x7ff

#define SEP_BOOT_TABLE_DESCRIPTOR_FLAGS 0x3
#define SEP_BOOT_ROM_PAGE_FLAGS 0x0004000000000687
#define SEP_BOOT_RAM_PAGE_FLAGS 0x0064000000000607
#define SEP_BOOT_DEVICE_PAGE_FLAGS 0x0064000000000603
#define SEP_BOOT_DEVICE_BLOCK_DESCRIPTOR 0x0064000000000601
#define SEP_BOOT_LOW_APERTURE_BLOCK_FLAGS 0x0064000000000601
#define SEP_BOOT_RUNTIME_WINDOW_BLOCK_FLAGS 0x0004000000000605

#define SEP_BOOT_MAIR_EL1 0x0000000000444f00
#define SEP_BOOT_TCR_EL1 0x000000034080a51c
#define SEP_BOOT_SCTLR_EARLY_BITS 0x1000

/*
 * The warm path (start.S): the word the runtime's deep-sleep path sets on its
 * way down, and the runtime's entry on the t8110 platform
 * (boot_platform.c), which is where the warm path re-enters it.
 */
#define SEP_BOOT_WARM_MARK 0x23d2e4804
#define SEP_BOOT_RUNTIME_ENTRY 0x340000000
#define SEP_BOOT_SCTLR_ENABLE_BITS 0x000d

#define SEP_BOOT_ROOT_INDEX(address) \
    (((address) >> SEP_BOOT_ROOT_SHIFT) & SEP_BOOT_TABLE_INDEX_MASK)
#define SEP_BOOT_PAGE_INDEX(address) \
    (((address) >> SEP_BOOT_PAGE_SHIFT) & SEP_BOOT_TABLE_INDEX_MASK)
#define SEP_BOOT_PAGE_DESCRIPTOR(address, flags) ((address) | (flags))
#define SEP_BOOT_DEVICE_BLOCK_TRANSLATE(address) \
    ((address) - SEP_BOOT_DEVICE_BLOCK_VA + SEP_BOOT_DEVICE_BLOCK_PA)

#endif
