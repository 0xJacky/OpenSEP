#include "open_secure_rom/optional_values.h"

#include <assert.h>

void __attribute__((noreturn)) sep_fatal_wait_loop(void) {
    assert(0 && "unexpected optional crypto fatal path");
    __builtin_unreachable();
}

int main(void) {
    static const sep_u8 expected[48] = {
        0xcb, 0x00, 0x75, 0x3f, 0x45, 0xa3, 0x5e, 0x8b,
        0xb5, 0xa0, 0x3d, 0x69, 0x9a, 0xc6, 0x50, 0x07,
        0x27, 0x2c, 0x32, 0xab, 0x0e, 0xde, 0xd1, 0x63,
        0x1a, 0x8b, 0x60, 0x5a, 0x43, 0xff, 0x5b, 0xed,
        0x80, 0x86, 0x07, 0x2b, 0xa1, 0xe7, 0xcc, 0x23,
        0x58, 0xba, 0xec, 0xa1, 0x34, 0xc8, 0x25, 0xa7,
    };
    const sep_optional_configuration_key48_t key =
        sep_optional_configuration_key48_from_sha384("abc", 3);
    assert(key.present == 1);
    for (sep_size_t index = 0; index < sizeof(key.bytes); ++index) {
        assert(key.bytes[index] == expected[index]);
    }
}
